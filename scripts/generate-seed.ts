// Writes supabase/migrations/20261019000300_cms_seed.sql from the site's
// current content (src/content/defaults.ts) and the section registry
// (src/content/schema.ts). Run with: npm run cms:seed
//
// Rows are inserted as both draft and published, so the live site looks
// exactly as it does today the moment the CMS is switched on. Existing rows
// are left alone, so running the migration again never overwrites edits.

import { writeFileSync } from "node:fs";
import { defaultContent } from "../src/content/defaults";
import { pageSchema, settingsSchema } from "../src/content/schema";

const json = (value: unknown) => `$json$${JSON.stringify(value)}$json$::jsonb`;
const text = (value: string) => `'${value.replace(/'/g, "''")}'`;

const out: string[] = [
  "-- Generated by scripts/generate-seed.ts from the site's existing content. Do not edit by hand.",
  "-- Inserts each page, section, setting and equipment item as both draft and published.",
  "",
];

let pageOrder = 0;
for (const [slug, page] of Object.entries(pageSchema)) {
  const content = defaultContent.pages[slug as keyof typeof defaultContent.pages];
  out.push(
    `insert into public.pages (slug, title, path, sort_order, draft, published, published_at)`,
    `values (${text(slug)}, ${text(page.label)}, ${text(page.path)}, ${pageOrder++}, ${json(content.seo)}, ${json(content.seo)}, now())`,
    `on conflict (slug) do nothing;`,
    "",
  );
  page.sections.forEach((section, i) => {
    const value = (content.sections as Record<string, unknown>)[section.key];
    if (value === undefined) throw new Error(`No default content for ${slug}.${section.key}`);
    out.push(
      `insert into public.page_sections (page_id, section_key, section_type, label, sort_order, draft, published, published_at)`,
      `select id, ${text(section.key)}, ${text(section.component)}, ${text(section.label)}, ${i}, ${json(value)}, ${json(value)}, now()`,
      `from public.pages where slug = ${text(slug)}`,
      `on conflict (page_id, section_key) do nothing;`,
      "",
    );
  });
}

for (const setting of settingsSchema) {
  const value = (defaultContent.settings as Record<string, unknown>)[setting.key];
  if (value === undefined) throw new Error(`No default content for setting ${setting.key}`);
  out.push(
    `insert into public.site_settings (setting_key, label, draft, published, published_at)`,
    `values (${text(setting.key)}, ${text(setting.label)}, ${json(value)}, ${json(value)}, now())`,
    `on conflict (setting_key) do nothing;`,
    "",
  );
}

defaultContent.equipment.forEach(({ id, ...item }, i) => {
  out.push(
    `insert into public.equipment (slug, sort_order, draft_sort_order, is_published, draft, published, published_at)`,
    `values (${text(id)}, ${i}, ${i}, true, ${json(item)}, ${json(item)}, now())`,
    `on conflict (slug) do nothing;`,
    "",
  );
});

writeFileSync(new URL("../supabase/migrations/20261019000300_cms_seed.sql", import.meta.url), out.join("\n"));
console.log("Wrote supabase/migrations/20261019000300_cms_seed.sql");
